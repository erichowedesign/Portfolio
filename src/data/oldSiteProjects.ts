const description = [
  "A short description of the project: what it is, who it was for, and what you contributed. Two or three sentences.",
];

function oldSiteProject(
  slug: string,
  title: string,
  client: string,
  year: string,
  gallery: ImageSlot[][],
): GalleryProject {
  const landscape = gallery.flat().find((img) => img.width && img.height && img.height / img.width < 0.7);
  const cover = landscape ?? gallery[0][0];
  return {
    kind: "gallery",
    slug,
    title,
    category: client,
    year,
    summary: "One-line description of the work shown.",
    tags: [],
    cover: { ...cover, label: title, aspect: "video" },
    meta: [
      { label: "Client", value: client },
      { label: "Year", value: year },
    ],
    description,
    gallery,
  };
}

